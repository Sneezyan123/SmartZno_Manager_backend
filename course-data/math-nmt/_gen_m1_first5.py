def L(id, mid, title, order, objectives, tags, theory, cards, hw, subtopics=None):
    return {
        "id": id, "moduleId": mid, "title": title, "slug": id, "order": order,
        "status": "ready", "objectives": objectives, "nmtTags": tags,
        "subtopics": subtopics or [], "theory": theory, "quizCards": cards, "homework": hw,
    }


def T(typ, content, items=None):
    d = {"type": typ, "content": content}
    if items is not None:
        d["items"] = items
    return d


def C(pid, pairs):
    out = []
    for i, p in enumerate(pairs, 1):
        item = {"id": f"{pid}-c{i:02d}", "front": p[0], "back": p[1]}
        if len(p) > 2 and p[2]:
            item["hint"] = p[2]
        out.append(item)
    return out


def S(hid, prompt, opts, ans, expl):
    keys = ["А", "Б", "В", "Г", "Д"]
    return {
        "id": hid, "type": "single", "prompt": prompt,
        "options": [{"key": keys[i], "text": opts[i]} for i in range(5)],
        "answer": ans, "explanation": expl,
    }


def O(hid, prompt, ans, expl):
    return {"id": hid, "type": "open", "prompt": prompt, "answer": str(ans), "explanation": expl}


def M(hid, prompt, left, right, ans, expl):
    return {
        "id": hid, "type": "match", "prompt": prompt,
        "left": [{"key": a, "text": b} for a, b in left],
        "right": [{"key": a, "text": b} for a, b in right],
        "answer": ans, "explanation": expl,
    }


