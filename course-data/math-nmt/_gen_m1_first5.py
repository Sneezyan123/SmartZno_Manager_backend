def write_lessons(lessons):
    for dest in DESTS:
        les_dir = dest / "lessons"
        les_dir.mkdir(parents=True, exist_ok=True)
        for les in lessons:
            with (les_dir / f"{les['id']}.json").open("w", encoding="utf-8") as f:
                json.dump(les, f, ensure_ascii=False, indent=2)
        print(f"Wrote {len(lessons)} detailed lessons → {dest}")


